-- ============================================================
-- BÚSSOLA — lado do negócio: empresas, anúncios e destaques
--
-- Modelo: registar empresa e publicar anúncios é gratuito e sem
-- limite. O único ponto de cobrança é o destaque de um anúncio,
-- por período, com pagamento único e sem renovação automática.
-- ============================================================

-- ---------- Empresas ----------
create table if not exists public.companies (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null check (category in (
    'Advogados','Imobiliárias','Eventos','Empregos','Serviços',
    'Formação','Associações','Contabilidade','Saúde','Outra')),
  city text,
  nif text,
  email text,
  phone text,
  about text,
  -- estado de verificação, espelha a fila do painel de admin
  verification text not null default 'pending'
    check (verification in ('pending','review','verified','rejected','suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.companies is 'Contas de empresa. O registo é gratuito: não existe subscrição.';

-- Quem pode gerir cada empresa. Tabela própria para permitir mais
-- do que um gestor (uma imobiliária tem vários agentes).
create table if not exists public.company_members (
  company_id uuid not null references public.companies(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'owner' check (role in ('owner','manager')),
  created_at timestamptz not null default now(),
  primary key (company_id, user_id)
);

-- ---------- Anúncios ----------
-- Tabela única para vagas, imóveis, eventos e serviços: o destaque
-- aplica-se da mesma forma a todos, e assim a chave estrangeira do
-- destaque é simples em vez de polimórfica.
create table if not exists public.listings (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  kind text not null check (kind in ('job','home','event','service')),
  title text not null,
  city text,
  price_cents int check (price_cents is null or price_cents >= 0),
  details jsonb not null default '{}'::jsonb,   -- campos próprios de cada tipo
  status text not null default 'draft'
    check (status in ('draft','review','published','paused','removed')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table public.listings is 'Anúncios. Publicar é gratuito e sem limite de quantidade.';

-- ---------- Pacotes de destaque ----------
-- Em tabela, para o admin poder mudar preços sem novo deploy.
create table if not exists public.boost_packages (
  id text primary key,                    -- d7 | d15 | d30
  name text not null,
  days int not null check (days > 0),
  price_cents int not null check (price_cents >= 0),
  description text,
  active boolean not null default true,
  sort int not null default 0
);
comment on table public.boost_packages is 'Catálogo de destaques. Valores em cêntimos, nunca em vírgula flutuante.';

