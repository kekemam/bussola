-- ---------- Destaques comprados ----------
create table if not exists public.boosts (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  package_id text not null references public.boost_packages(id),
  days int not null check (days > 0),
  price_cents int not null check (price_cents >= 0),
  starts_at timestamptz not null default now(),
  ends_at timestamptz not null,
  status text not null default 'active'
    check (status in ('active','expired','refunded','cancelled')),
  receipt_no bigint generated by default as identity,  -- numeração sempre crescente
  payment_ref text,                                     -- referência do fornecedor de pagamento
  created_at timestamptz not null default now(),
  constraint periodo_valido check (ends_at > starts_at)
);
comment on table public.boosts is
  'Compras de destaque. Pagamento único: não há renovação automática.';
comment on column public.boosts.receipt_no is
  'Número de recibo. Identity garante que cresce sempre, mesmo com inserções concorrentes.';

create index if not exists idx_listings_company on public.listings(company_id);
create index if not exists idx_listings_publicos on public.listings(kind, city) where status = 'published';
create index if not exists idx_boosts_listing on public.boosts(listing_id, ends_at desc);
create index if not exists idx_boosts_ativos on public.boosts(ends_at) where status = 'active';
create index if not exists idx_members_user on public.company_members(user_id);
